-- =====================================================================
-- StudyFlow - Oracle Autonomous Database SQL DDL Schema Initialization
-- Architecture: Academic Year, Specific/Common Branches, Divisions, & Lab Batches
-- Compatible with Oracle Database 19c / 21c / 23c / Autonomous DB
-- =====================================================================

-- 1. TEACHERS TABLE
CREATE TABLE teachers (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR2(120) NOT NULL,
    email          VARCHAR2(255) NOT NULL,
    password_hash  VARCHAR2(255) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_teachers_email UNIQUE (email)
);

-- 2. STUDENTS TABLE
-- First Year (FE) uses branch = 'Common', SE/TE/BE use 'CE', 'IT', etc.
-- Batches represent lab sub-groups like 'E1', 'E2', 'A1'.
-- access_code example: 'FE-Common-E-E1-36' or 'SE-CE-A-A1-12'
CREATE TABLE students (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR2(120) NOT NULL,
    academic_year  VARCHAR2(10) NOT NULL CHECK (academic_year IN ('FE', 'SE', 'TE', 'BE')),
    branch         VARCHAR2(30) NOT NULL, -- 'Common' for FE, 'CE', 'IT', 'MECH', etc. for SE/TE/BE
    division       VARCHAR2(5) NOT NULL,  -- 'A', 'B', 'C', 'D', 'E'
    batch          VARCHAR2(10) NOT NULL, -- 'E1', 'E2', 'A1', 'A2', etc.
    roll_number    VARCHAR2(30) NOT NULL,
    access_code    VARCHAR2(100) NOT NULL,
    password_hash  VARCHAR2(255) DEFAULT NULL,
    is_first_login NUMBER(1) DEFAULT 1 CHECK (is_first_login IN (0, 1)),
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_students_access_code UNIQUE (access_code)
);

-- Fast lookup indexes for access code login & division rosters
CREATE INDEX idx_students_access_code ON students(UPPER(access_code));
CREATE INDEX idx_students_hierarchy ON students(academic_year, branch, division, batch);

-- 3. CLASSES TABLE
-- class_type is constrained to 'Lecture' or 'Lab/Practical'
CREATE TABLE classes (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id     NUMBER NOT NULL,
    academic_year  VARCHAR2(10) NOT NULL CHECK (academic_year IN ('FE', 'SE', 'TE', 'BE')),
    branch         VARCHAR2(30) NOT NULL,
    division       VARCHAR2(5) NOT NULL,
    subject_name   VARCHAR2(120) NOT NULL,
    class_type     VARCHAR2(20) NOT NULL CHECK (class_type IN ('Lecture', 'Lab/Practical')),
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_classes_teacher FOREIGN KEY (teacher_id) REFERENCES teachers(id) ON DELETE CASCADE
);

CREATE INDEX idx_classes_lookup ON classes(academic_year, branch, division, subject_name);
CREATE INDEX idx_classes_teacher ON classes(teacher_id);

-- 4. CLASS_BATCHES TABLE
-- Stores specific lab sub-batches targeted by a class (e.g. 'E1', 'E2')
CREATE TABLE class_batches (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id       NUMBER NOT NULL,
    batch_name     VARCHAR2(10) NOT NULL, -- 'E1', 'E2', etc.
    CONSTRAINT fk_cb_class FOREIGN KEY (class_id) REFERENCES classes(id) ON DELETE CASCADE,
    CONSTRAINT uq_class_batch UNIQUE (class_id, batch_name)
);

CREATE INDEX idx_class_batches_lookup ON class_batches(class_id, batch_name);

-- 5. STUDY_MATERIALS TABLE
-- If batch_target_id IS NULL -> Available to the whole division (e.g. Lecture Notes)
-- If batch_target_id IS NOT NULL -> Targeted strictly to that specific Lab Batch (e.g. Lab Manual E1)
CREATE TABLE study_materials (
    id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id         NUMBER NOT NULL,
    batch_target_id  NUMBER DEFAULT NULL,
    unit_number      VARCHAR2(50),
    title            VARCHAR2(255) NOT NULL,
    file_url         VARCHAR2(500) NOT NULL,
    file_type        VARCHAR2(20) DEFAULT 'pdf',
    upload_timestamp TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sm_class FOREIGN KEY (class_id) REFERENCES classes(id) ON DELETE CASCADE,
    CONSTRAINT fk_sm_batch FOREIGN KEY (batch_target_id) REFERENCES class_batches(id) ON DELETE SET NULL
);

CREATE INDEX idx_sm_class_target ON study_materials(class_id, batch_target_id);
CREATE INDEX idx_sm_unit ON study_materials(class_id, unit_number);

-- 6. ATTENDANCE TABLE
-- Tracks daily attendance per student per class session
CREATE TABLE attendance (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      NUMBER NOT NULL,
    class_id        NUMBER NOT NULL,
    attendance_date DATE NOT NULL,
    status          VARCHAR2(10) NOT NULL CHECK (status IN ('present', 'absent', 'late')),
    marked_at       TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_att_student FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    CONSTRAINT fk_att_class FOREIGN KEY (class_id) REFERENCES classes(id) ON DELETE CASCADE,
    CONSTRAINT uq_att_student_class_date UNIQUE (student_id, class_id, attendance_date)
);

CREATE INDEX idx_att_student_class ON attendance(student_id, class_id, attendance_date);
CREATE INDEX idx_att_report ON attendance(class_id, attendance_date, status);

-- 7. NOTICES TABLE
-- Teacher announcements targeted to a year/branch/division.
-- If batch IS NULL -> visible to the whole division; otherwise only that lab batch.
CREATE TABLE notices (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id     NUMBER NOT NULL,
    academic_year  VARCHAR2(10) NOT NULL CHECK (academic_year IN ('FE', 'SE', 'TE', 'BE')),
    branch         VARCHAR2(30) NOT NULL,
    division       VARCHAR2(5) NOT NULL,
    batch          VARCHAR2(10) DEFAULT NULL, -- NULL = whole division
    title          VARCHAR2(200) NOT NULL,
    body           VARCHAR2(2000) NOT NULL,
    is_pinned      NUMBER(1) DEFAULT 0 CHECK (is_pinned IN (0, 1)),
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notices_teacher FOREIGN KEY (teacher_id) REFERENCES teachers(id) ON DELETE CASCADE
);

CREATE INDEX idx_notices_target ON notices(academic_year, branch, division, batch);

