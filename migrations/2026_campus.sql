-- Run once against an existing StudyFlow Oracle database before this release.
-- Existing academic records are preserved. Fresh installs also need this file.
CREATE TABLE campus_items (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind VARCHAR2(20) NOT NULL CHECK (kind IN ('timetable','assignment','submission','correction')),
  owner_id NUMBER NOT NULL,
  class_id NUMBER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  payload VARCHAR2(4000) NOT NULL CHECK (payload IS JSON)
);
CREATE INDEX idx_campus_class ON campus_items(class_id, kind);
