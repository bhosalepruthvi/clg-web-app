-- Apply once after the campus and discussion migrations, on new and existing databases.
CREATE TABLE app_records (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind VARCHAR2(30) NOT NULL,
  owner_id NUMBER NOT NULL,
  payload VARCHAR2(4000) NOT NULL CHECK (payload IS JSON)
);
CREATE INDEX idx_app_records_kind_owner ON app_records(kind, owner_id);
