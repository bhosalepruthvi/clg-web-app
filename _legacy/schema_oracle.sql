-- 1. TEACHERS TABLE
CREATE TABLE teachers (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR2(120) NOT NULL,
    email          VARCHAR2(255) NOT NULL,
    password_hash  VARCHAR2(255) NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_teachers_email UNIQUE (email)
);

-- 2. SUBJECTS TABLE
CREATE TABLE subjects (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR2(100) NOT NULL,
    year           NUMBER(1) NOT NULL CHECK (year BETWEEN 1 AND 4),
    semester       NUMBER(2) NOT NULL CHECK (semester BETWEEN 1 AND 8),
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_subject_year_sem UNIQUE (name, year, semester)
);

-- 3. TEACHER_SUBJECTS (Many-to-Many Mapping)
CREATE TABLE teacher_subjects (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id     NUMBER NOT NULL,
    subject_id     NUMBER NOT NULL,
    assigned_at    TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ts_teacher FOREIGN KEY (teacher_id) REFERENCES teachers(id) ON DELETE CASCADE,
    CONSTRAINT fk_ts_subject FOREIGN KEY (subject_id) REFERENCES subjects(id) ON DELETE CASCADE,
    CONSTRAINT uq_teacher_subject UNIQUE (teacher_id, subject_id)
);

-- 4. STUDENTS TABLE
CREATE TABLE students (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR2(120) NOT NULL,
    division       VARCHAR2(5) NOT NULL,
    roll_number    VARCHAR2(30) NOT NULL,
    access_code    VARCHAR2(64) NOT NULL,
    password_hash  VARCHAR2(255) DEFAULT NULL,
    is_first_login NUMBER(1) DEFAULT 1 CHECK (is_first_login IN (0, 1)),
    created_at     TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_students_access_code UNIQUE (access_code)
);

-- Index for instant lookup on student access code during login
CREATE INDEX idx_students_access_code ON students(UPPER(access_code));
CREATE INDEX idx_students_div_roll ON students(division, roll_number);

-- 5. STUDY_MATERIALS TABLE
CREATE TABLE study_materials (
    id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id       NUMBER NOT NULL,
    teacher_id       NUMBER NOT NULL,
    unit_number      VARCHAR2(50),
    title            VARCHAR2(255) NOT NULL,
    description      VARCHAR2(1000),
    file_url         VARCHAR2(500) NOT NULL,
    file_type        VARCHAR2(20) DEFAULT 'pdf',
    upload_timestamp TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sm_subject FOREIGN KEY (subject_id) REFERENCES subjects(id) ON DELETE CASCADE,
    CONSTRAINT fk_sm_teacher FOREIGN KEY (teacher_id) REFERENCES teachers(id) ON DELETE CASCADE
);

CREATE INDEX idx_sm_subject_unit ON study_materials(subject_id, unit_number);
CREATE INDEX idx_sm_teacher ON study_materials(teacher_id);

-- 6. ATTENDANCE TABLE
CREATE TABLE attendance (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id     NUMBER NOT NULL,
    subject_id     NUMBER NOT NULL,
    attendance_date DATE NOT NULL,
    status         VARCHAR2(10) NOT NULL CHECK (status IN ('present', 'absent', 'late')),
    marked_at      TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_att_student FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    CONSTRAINT fk_att_subject FOREIGN KEY (subject_id) REFERENCES subjects(id) ON DELETE CASCADE,
    CONSTRAINT uq_student_subject_date UNIQUE (student_id, subject_id, attendance_date)
);

CREATE INDEX idx_att_lookup ON attendance(student_id, subject_id, attendance_date);
CREATE INDEX idx_att_stats ON attendance(subject_id, attendance_date, status);
